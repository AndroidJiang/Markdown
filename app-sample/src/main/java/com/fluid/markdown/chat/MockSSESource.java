    // ==================== 纯文本 ====================

    public static String buildSimpleText() {
        return "这是一个流式 Markdown 文本回复示例！\n\n" +
                "支持以下格式：\n\n" +
                "### 文本样式\n\n" +
                "**加粗文本**、*斜体文本*、~~删除线~~、`行内代码`\n\n" +
                "### 列表\n\n" +
                "- 无序列表项 1\n" +
                "- 无序列表项 2\n" +
                "  - 子列表项\n" +
                "\n1. 有序列表 1\n" +
                "2. 有序列表 2\n\n" +
                "### 引用\n\n" +
                "> 这是一段引用文本，用于展示引用效果。\n" +
                "> 可以跨多行显示。\n\n" +
                "### 代码块\n\n" +
                "```java\n" +
                "public class Hello {\n" +
                "    public static void main(String[] args) {\n" +
                "        System.out.println(\"Hello, World!\");\n" +
                "    }\n" +
                "}\n" +
                "```\n\n" +
                "### 表格\n\n" +
                "| 功能 | 支持 | 说明 |\n" +
                "|------|------|------|\n" +
                "| 加粗 | 是 | **text** |\n" +
                "| 斜体 | 是 | *text* |\n" +
                "| 代码 | 是 | `code` |\n\n" +
                "---\n\n" +
                "以上就是流式 Markdown 的渲染效果，文本会逐字显示，体验和千问一致！";
    }
